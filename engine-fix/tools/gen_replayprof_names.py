"""gen_replayprof_names.py - writes src/replayprof_names.h (RPF replay profiler name tables). stdlib only.

    py -I tools/gen_replayprof_names.py [backend.md] [d3d12.h]

* KTGL token names (185): section 8 of notes/renderer/backend.md (main branch; the table `| op | handler | name | ...`).
* D3D12 vtable method names in slot order (IUnknown first) from the Windows SDK d3d12.h C vtables:
  ID3D12GraphicsCommandList7, ID3D12Device10, ID3D12CommandQueue, ID3D12Fence1, ID3D12Resource2.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BK = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(r"notes\renderer\backend.md")
H = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else pathlib.Path(
    r"tools\msvc\Windows Kits\10\Include\10.0.22621.0\um\d3d12.h")

tok = {}
for line in BK.read_text(encoding="utf-8").splitlines():
    m = re.match(r"^\| ([0-9A-F]{2}) \| ([0-9A-F]+) \| (\w+) \|", line)
    if m:
        tok[int(m.group(1), 16)] = (m.group(3), int(m.group(2), 16))
assert len(tok) == 185 and sorted(tok) == list(range(185)), len(tok)

s = H.read_text(encoding="latin1")


def meths(name):
    m = re.search(r"typedef struct %sVtbl\s*\{(.*?)\}\s*%sVtbl;" % (name, name), s, re.S)
    assert m, name
    return [b for _, b in re.findall(r"DECLSPEC_XFGVIRT\((\w+),\s*(\w+)\)", m.group(1))]


sets = [("kListNames", "ID3D12GraphicsCommandList7"), ("kDeviceNames", "ID3D12Device10"), ("kQueueNames", "ID3D12CommandQueue"),
        ("kFenceNames", "ID3D12Fence1"), ("kResourceNames", "ID3D12Resource2")]
out = ["// replayprof_names.h - GENERATED by tools/gen_replayprof_names.py (do not edit). RPF replay profiler name tables.",
       "#pragma once", "#include <cstdint>", "", "namespace replayprof {", "",
       "// KTGL token handler table 3C02220 (v2.02): name + handler RVA (notes/renderer/backend.md section 8)",
       "struct TokName { const char* name; uint32_t rva; };", "constexpr int kTokens = 185;",
       "constexpr TokName kTokNames[kTokens] = {"]
for i in range(185):
    out.append('    {"%s", 0x%X},  // %02X' % (tok[i][0], tok[i][1], i))
out.append("};")
for var, iface in sets:
    ms = meths(iface)
    out += ["", "// %s (%d slots, d3d12.h 10.0.22621)" % (iface, len(ms)), "constexpr int %sN = %d;" % (var, len(ms)),
            "constexpr const char* %s[%d] = {" % (var, len(ms))]
    for i in range(0, len(ms), 4):
        out.append("    " + " ".join('"%s",' % x for x in ms[i:i + 4]))
    out.append("};")
out += ["", "}  // namespace replayprof", ""]
(ROOT / "src" / "replayprof_names.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
print("wrote src/replayprof_names.h: 185 tokens, " + ", ".join("%s %d" % (i, len(meths(i))) for _, i in sets))
