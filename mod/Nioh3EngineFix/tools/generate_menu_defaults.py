"""Embed shipped defaults; reset must not copy a player's edited INI or stale catalog fallback."""
from pathlib import Path
import configparser,json,sys
root=Path(__file__).resolve().parents[1]
entries=[]
for path,prefix,only in [(root/'Nioh3EngineFix.ini','',None),(root.parent/'Nioh3Training/Nioh3Training.ini','Training.',{'Practice'})]:
 c=configparser.ConfigParser(interpolation=None,strict=False,inline_comment_prefixes=(';',));c.optionxform=str;c.read(path,encoding='utf-8-sig')
 for section in c.sections():
  if only is not None and section not in only:continue
  for key,value in c.items(section):entries.append((prefix+section,key,value.strip()))
text='// Generated by tools/generate_menu_defaults.py from packaged INIs.\n#pragma once\nnamespace shipped_defaults {\nstruct Entry { const char *section,*key,*value; };\ninline constexpr Entry kEntries[] = {\n'
for row in entries:text+='    {'+', '.join(json.dumps(x) for x in row)+'},\n'
text+='};\ninline const char* Get(const char* section,const char* key,const char* fallback) {\n    for(const auto& e:kEntries) if(!strcmp(e.section,section)&&!strcmp(e.key,key)) return e.value;\n    return fallback;\n}\n}\n'
p=root/'src/menu_shipped_defaults.h'
if '--check' in sys.argv:
 assert p.read_text()==text,'shipped default header differs from packaged INIs'
 print('PASS shipped-default header: '+str(len(entries))+' values')
else:p.write_text(text)
