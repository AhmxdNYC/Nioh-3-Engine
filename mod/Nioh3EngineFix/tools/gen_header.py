"""gen_header.py - generate src/patches_gen.h from patches.json (the single source of truth).

    py tools/gen_header.py            # (re)write src/patches_gen.h
    py tools/gen_header.py --check    # exit 1 if src/patches_gen.h is out of date

stdlib only. tests/test_patterns.py imports render() to check the header is in sync.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "patches.json"
HDR_PATH = ROOT / "src" / "patches_gen.h"

TARGETS = ["none", "caveFps", "caveScale", "caveLim", "caveTier", "caveMenu", "hookPeek", "caveL1", "fgWait", "caveWakeGate",
           "caveGallop", "cavePP", "caveFPC", "caveAabb", "caveM1", "caveX1", "caveE1A", "caveE1B", "caveW6", "caveW6Wake",
           "caveIkKick", "caveIkPadWait", "caveTsL", "caveTsW", "caveTsB", "caveTsP",
           "caveWs0", "caveWs1", "caveWs2", "caveWs3", "caveWs4", "caveWs5", "caveWsSleep", "caveEdKick", "caveEdJoin", "caveGf1", "caveGf2", "caveWL",
           "caveDs", "caveCP", "caveSPF", "caveSprG", "caveSprU",
           "caveDL", "caveMQ", "capPt1Acq", "capPt1Rel", "cavePt1B", "cavePt1C", "cavePt1D",
           "caveGl1A", "caveGl1B", "caveLdWait", "caveLdSig",
           "caveBpoQA", "caveBpoQB", "caveBpoL1", "caveBpoL2", "caveBpoV",
           "caveJtJob", "caveJtWait", "caveJtWake1", "caveJtWakeAll",
           "caveFgcSrc", "caveFgcDst", "caveFgp", "caveSiW", "caveSiS",
           "caveMpcsA", "caveMpcsB", "caveMpcsC",
           "caveVsmaEntry", "caveVsmaBudget", "caveVsmaBind", "caveRco",
           "caveGiScale", "caveMeshLod", "caveFxSim", "caveFxDraw", "caveMW", "caveMWWake", "caveRDWait", "caveRDWake"]
DATAS = ["none", "ticks120", "ticks60", "r1Timeout"]
KINDS = {"bytes": "Bytes", "call": "Call", "ripload": "RipLoad", "jmp": "Jmp", "vptr": "VPtr", "check": "Check"}
READS = {None: "None", "iat_disp32@2": "IatDisp32At2", "callee_rel32@1": "CalleeRel32At1", "callee_rel32@6": "CalleeRel32At6"}


def hx(s):
    return [int(x, 16) for x in s.split()]


def carr(name, bs):
    return "static const uint8_t %s[] = { %s };" % (name, ", ".join("0x%02X" % b for b in bs))


def render(doc):
    out = []
    w = out.append
    w("// GENERATED by tools/gen_header.py from patches.json - DO NOT EDIT. Regenerate after changing patches.json.")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace gen {")
    w("")
    w("enum class Kind : uint8_t { Bytes, Call, RipLoad, Jmp, VPtr, Check };  // Check: verified, never written")
    w("enum class Target : uint8_t { %s };" % ", ".join(TARGETS))
    w("enum class Data : uint8_t { %s };" % ", ".join(DATAS))
    w("enum class Reads : uint8_t { None, IatDisp32At2, CalleeRel32At1, CalleeRel32At6 };")
    w("")
    w("struct Site {")
    w("    const char* id;       // patch id (W1, W2a, P1, ...)")
    w("    const char* group;    // INI/atomicity group")
    w("    uint32_t rva;         // expected RVA in the known build (sanity check only; sites are found by pattern)")
    w("    uint8_t len;          // bytes replaced at the site")
    w("    const uint8_t* orig;  // original bytes (len)")
    w("    const char* pattern;  // AOB, '??' = wildcard")
    w("    uint8_t offset;       // site offset inside the pattern")
    w("    Kind kind;")
    w("    const uint8_t* repl;  // Kind::Bytes: replacement (len)")
    w("    Target target;        // Kind::Call: cave entry reached through a near trampoline")
    w("    uint8_t callAt;       // Kind::Call: offset of the E8 inside the site (bytes before it are 90)")
    w("    uint8_t opcode[2];    // Kind::RipLoad: opcode + modrm, followed by rel32 to the near data slot")
    w("    Data data;            // Kind::RipLoad: near data slot")
    w("    Reads reads;          // value taken from the original bytes before patching")
    w("    uint32_t expectRva;   // Kind::VPtr: original pointer target RVA; E8 sites with \"callee\": expected callee RVA; else 0")
    w("};")
    w("")
    w("// original code the caves depend on beyond their own site (checked on the known build before a group is written)")
    w("struct Dep {")
    w("    const char* group;")
    w("    uint32_t rva;")
    w("    uint32_t len;")
    w("    const uint8_t* bytes;  // exact bytes, or nullptr -> compare the FNV-1a 32 hash")
    w("    uint32_t fnv1a;")
    w("};")
    w("")
    b = doc["build"]
    w("constexpr uint32_t kBuildTimestamp = %s;   // %s" % (b["timestamp"], b["name"]))
    w("constexpr uint32_t kBuildSizeOfImage = %s;" % b["size_of_image"])
    w("")
    for s in doc["sites"]:
        if s["kind"] == "vptr":
            continue
        w(carr("orig_%s" % s["id"], hx(s["orig"])))
        if s["kind"] == "bytes":
            w(carr("repl_%s" % s["id"], hx(s["new"])))
    w("")
    w("static const Site kSites[] = {")
    for s in doc["sites"]:
        kind = KINDS[s["kind"]]
        repl = "repl_%s" % s["id"] if s["kind"] == "bytes" else "nullptr"
        target = s.get("target", "none")
        call_at = int(s.get("call_at", 0))
        op = hx(s["opcode"]) if "opcode" in s else [0, 0]
        data = s.get("data", "none")
        reads = READS[s.get("reads")]
        expect = s.get("vtarget", s.get("callee", "0x0"))
        assert target in TARGETS and data in DATAS
        orig = "nullptr" if s["kind"] == "vptr" else "orig_%s" % s["id"]
        w('    { "%s", "%s", %s, %d, %s, "%s", %d, Kind::%s, %s, Target::%s, %d, { 0x%02X, 0x%02X }, Data::%s, Reads::%s, %s },'
          % (s["id"], s["group"], s["rva"], s["len"], orig, s.get("pattern", ""), s.get("offset", 0), kind, repl, target,
             call_at, op[0], op[1], data, reads, expect))
    w("};")
    w("constexpr int kNumSites = sizeof(kSites) / sizeof(kSites[0]);")
    w("")
    deps = doc.get("deps", [])
    for i, d in enumerate(deps):
        if "bytes" in d:
            w(carr("dep_%d" % i, hx(d["bytes"])))
    w("static const Dep kDeps[] = {")
    for i, d in enumerate(deps):
        ln = len(hx(d["bytes"])) if "bytes" in d else int(d["len"])
        w('    { "%s", %s, %d, %s, %s },  // %s' % (d["group"], d["rva"], ln, ("dep_%d" % i) if "bytes" in d else "nullptr",
                                              d.get("fnv1a", "0"), d.get("what", "")))
    w("};")
    w("constexpr int kNumDeps = sizeof(kDeps) / sizeof(kDeps[0]);")
    w("")
    w("} // namespace gen")
    w("")
    return "\n".join(out)


def main():
    doc = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    text = render(doc)
    if "--check" in sys.argv:
        cur = HDR_PATH.read_text(encoding="utf-8") if HDR_PATH.exists() else ""
        if cur != text:
            print("patches_gen.h is OUT OF DATE - run: py tools/gen_header.py")
            return 1
        print("patches_gen.h in sync")
        return 0
    HDR_PATH.parent.mkdir(parents=True, exist_ok=True)
    HDR_PATH.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", HDR_PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
