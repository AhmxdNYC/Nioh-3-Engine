r"""gen_rvas.py - the pattern table behind Grva() (src/gamerva.h): rvas.json -> src/rvas_gen.h.

    py tools/gen_rvas.py DUMP          # add patterns for every new fixed RVA the sources use (needs capstone + numpy)
    py tools/gen_rvas.py DUMP --all    # re-derive every entry
    py -I tools/gen_rvas.py --check    # exit 1 if rvas_gen.h is stale or a fixed RVA of EngineFix is not in rvas.json
    py -I tools/gen_rvas.py            # rvas.json -> src/rvas_gen.h only

DUMP = decrypted image of the running game (file offset == RVA; the on-disk exe keeps .text encrypted). The RVA list comes
from tools/check_fixed_rvas.py (every base + fixed RVA in mod/Nioh3EngineFix/src, Grva-wrapped or not); profiling label
tables (replayprof_names.h) are left out. Patterns follow mod/Nioh3BossRematch/tools/derive_sites.py (via tools/aob_audit.py):
unique in the executable sections, rip-relative displacements and branch targets wildcarded.
"""
import json
import pathlib
import struct
import sys

MOD = pathlib.Path(__file__).resolve().parent.parent
ROOT = MOD.parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import check_fixed_rvas  # noqa: E402

JSON = MOD / "rvas.json"
HDR = MOD / "src" / "rvas_gen.h"
SKIP = ()


def wanted():
    uses, _ = check_fixed_rvas.scan()
    out = {}
    for u in uses:
        where = u.get("used_at", "%s:%d" % (u["file"], u["line"]))
        if u["kind"] == "bound" or not where.startswith("mod/%s/" % MOD.name) or any(s in u["file"] for s in SKIP):
            continue
        out.setdefault(u["rva"], set()).add(where.split("/", 3)[3].rsplit(":", 1)[0])
    return out


def render(doc):
    kinds = {"code": "kCode", "global": "kGlobal", "iat": "kIat", "none": "kNone"}
    rows = []
    for e in doc["rvas"]:
        rows.append('    {0x%X, %s, %s, %d, 0x%X, %d, %d, %d, %s},  // %s' % (
            int(e["rva"], 16), kinds[e["kind"]], json.dumps(e.get("pattern", "")), e.get("offset", 0), int(e.get("anchor", "0x0"), 16),
            e.get("disp_off", 0), e.get("insn_len", 0), e.get("addend", 0), json.dumps(e.get("iat", "")),
            ", ".join(e.get("used_in", []))[:90]))
    return "\n".join([
        "// GENERATED by tools/gen_rvas.py from rvas.json - do not edit. Pattern table behind Grva() (gamerva.h / gamerva.cpp).",
        "#pragma once",
        "#include <cstdint>",
        "namespace gamerva::rvas {",
        "constexpr uint32_t kBuildTimestamp = %s, kBuildSizeOfImage = %s;" % (doc["build"]["timestamp"], doc["build"]["size_of_image"]),
        "enum Kind : uint8_t { kCode, kGlobal, kIat, kNone };",
        "struct Def {",
        "    uint32_t rva;        // v2.02 RVA (sorted)",
        "    Kind kind;",
        "    const char* pattern;  // code: match starts offset bytes before rva; global: offset bytes before the anchor",
        "    int16_t offset;",
        "    uint32_t anchor;      // global: v2.02 RVA of the rip-relative instruction",
        "    uint8_t dispOff, insnLen;",
        "    int32_t addend;",
        "    const char* iat;      // iat: \"dll!func\"",
        "};",
        "constexpr Def kDefs[] = {",
    ] + rows + [
        "};",
        "constexpr int kCount = (int)(sizeof(kDefs) / sizeof(kDefs[0]));",
        "}  // namespace gamerva::rvas",
        "",
    ])


def derive(dump, todo, doc):
    import multiprocessing as mp
    import aob_audit
    img = pathlib.Path(dump).read_bytes()
    pe = struct.unpack_from("<I", img, 0x3C)[0]
    ts, soi = struct.unpack_from("<I", img, pe + 8)[0], struct.unpack_from("<I", img, pe + 24 + 56)[0]
    if (ts, soi) != (int(doc["build"]["timestamp"], 16), int(doc["build"]["size_of_image"], 16)):
        raise SystemExit("dump build %X/%X is not rvas.json's build" % (ts, soi))
    secs = aob_audit.sections(img)
    iat = aob_audit.iat_names(img)

    def is_exec(r):
        return any(va <= r < va + vs and ex for _, va, vs, ex in secs)

    out = {}
    for r in todo:
        if r in iat:
            out[r] = {"kind": "iat", "iat": iat[r]}
    jobs = [(r, is_exec(r)) for r in todo if r not in out]
    with mp.Pool(max(1, mp.cpu_count() - 2), initializer=aob_audit.init, initargs=(img,)) as pool:
        for res in pool.imap_unordered(aob_audit.work, jobs, chunksize=4):
            r = res["rva"]
            if not res["unique"]:
                out[r] = {"kind": "none", "why": res.get("why", "")}
            elif res["kind"] == "code":
                out[r] = {"kind": "code", "pattern": res["pattern"], "offset": res["offset"]}
            else:
                out[r] = {"kind": "global", "pattern": res["pattern"], "offset": res["offset"], "anchor": "0x%X" % res["anchor"],
                          "disp_off": res["disp_off"], "insn_len": res["insn_len"], "addend": res.get("addend", 0), "what": res["what"]}
    return out


def main():
    a = sys.argv[1:]
    args = [x for x in a if not x.startswith("--")]
    doc = json.loads(JSON.read_text()) if JSON.exists() else {
        "_comment": "GENERATED by tools/gen_rvas.py (patterns from a decrypted dump); src/rvas_gen.h is generated from this file.",
        "build": {"timestamp": "0x6AA7C106", "size_of_image": "0x52FB000"}, "rvas": []}
    want = wanted()
    have = {int(e["rva"], 16): e for e in doc["rvas"]}
    if "--check" in a:
        bad = 0
        missing = sorted(set(want) - set(have))
        if missing:
            print("NOT in rvas.json (run tools/gen_rvas.py DUMP): " + " ".join("%X" % r for r in missing))
            bad = 1
        if not HDR.exists() or HDR.read_text() != render(doc):
            print("src/rvas_gen.h is out of date (run tools/gen_rvas.py)")
            bad = 1
        print("rvas.json: %d entries, %d fixed RVAs used, %d missing" % (len(have), len(want), len(missing)))
        return bad
    if args:
        todo = sorted(want) if "--all" in a else sorted(set(want) - set(have))
        for r, e in derive(args[0], todo, doc).items():
            have[r] = dict({"rva": "0x%X" % r}, **e)
    for r, e in have.items():
        if r in want:
            e["used_in"] = sorted(want[r])
    doc["rvas"] = [have[r] for r in sorted(have)]
    JSON.write_text(json.dumps(doc, indent=1) + "\n")
    HDR.write_text(render(doc))
    kinds = {}
    for e in doc["rvas"]:
        kinds[e["kind"]] = kinds.get(e["kind"], 0) + 1
    print("rvas.json: %d entries (%s), %d fixed RVAs used by the sources" % (
        len(doc["rvas"]), ", ".join("%s %d" % kv for kv in sorted(kinds.items())), len(want)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
