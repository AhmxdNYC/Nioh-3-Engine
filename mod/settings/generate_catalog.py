"""Emit C++ UI metadata from the reviewed per-key catalog; --check never writes."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
CATALOG = json.loads((ROOT / 'mod/settings/catalog.json').read_text())
def quoted(text):
    return json.dumps(text, ensure_ascii=True)

def render(mod, data):
    lines = ['// Generated by mod/settings/generate_catalog.py; edit catalog.json.',
        '#pragma once', '#include "../../settings/store.h"',
        'const char* const kConfigGroups[] = {' + ', '.join(quoted(s) for s in data['groups']) + '};',
        '// user #13296: plain group names for the menus (kConfigGroups stays the ini section name)',
        'const char* const kConfigGroupLabels[] = {' + ', '.join(quoted(s) for s in data.get('groupLabels', data['groups'])) + '};',
        'const setting_ui::Def kConfigSettings[] = {']
    for row in data['settings']:
        fields = [quoted(row[k]) for k in ('section', 'key', 'label', 'default')]
        fields += ['setting_ui::Kind::' + row['kind'].title(), str(row['lo']), str(row['hi']), str(row['step']),
            quoted(row['choices']), 'setting_ui::Apply::' + row['mode'], quoted(row['live']),
            row['legacy'] or '-1', str(row['group']), str(row['experimental']).lower(), quoted(row['help'])]
        lines.append('    {' + ', '.join(fields) + '},')
    lines += ['};', 'constexpr int kConfigN = (int)(sizeof(kConfigSettings) / sizeof(kConfigSettings[0]));',
        'constexpr int kConfigGroupN = (int)(sizeof(kConfigGroups) / sizeof(kConfigGroups[0]));',
        'setting_ui::Store<kConfigN> g_configValues;', '']
    return '\n'.join(lines)

def main():
    for mod, data in CATALOG.items():
        target = ROOT / 'mod' / mod / 'src/settings_catalog.h'
        expected = render(mod, data)
        if '--check' in sys.argv:
            if not target.exists() or target.read_text() != expected:
                raise SystemExit('stale generated catalog: ' + str(target))
        else:
            target.write_text(expected)
    print('PASS: generated settings catalogs' + (' match' if '--check' in sys.argv else ' written'))

if __name__ == '__main__':
    main()
