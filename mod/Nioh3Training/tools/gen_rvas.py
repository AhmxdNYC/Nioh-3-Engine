r"""gen_rvas.py (Nioh3Training) - the pattern table behind Grva() (src/gamerva.h): rvas.json -> src/rvas_gen.h (C).

    py tools/gen_rvas.py DUMP          # add patterns for every new fixed RVA the sources use (needs capstone + numpy)
    py tools/gen_rvas.py DUMP --all    # re-derive every entry
    py -I tools/gen_rvas.py --check    # exit 1 if rvas_gen.h is stale or a fixed RVA of Training is not in rvas.json
    py -I tools/gen_rvas.py            # rvas.json -> src/rvas_gen.h only

Same derivation as mod/Nioh3EngineFix/tools/gen_rvas.py (which this script runs with Training's paths and a C renderer);
DUMP = decrypted image of the game (file offset == RVA), e.g. Nioh3.dump.bin.
"""
import importlib.util
import json
import pathlib
import sys

MOD = pathlib.Path(__file__).resolve().parent.parent
ROOT = MOD.parent.parent
spec = importlib.util.spec_from_file_location("ef_gen_rvas", ROOT / "mod" / "Nioh3EngineFix" / "tools" / "gen_rvas.py")
g = importlib.util.module_from_spec(spec)
sys.path.insert(0, str(ROOT / "tools"))
spec.loader.exec_module(g)


def render(doc):
    kinds = {"code": "GRV_CODE", "global": "GRV_GLOBAL", "iat": "GRV_IAT", "none": "GRV_NONE"}
    rows = []
    for e in doc["rvas"]:
        rows.append('    {0x%X, %s, %s, %d, 0x%X, %d, %d, %d, %s},  // %s' % (
            int(e["rva"], 16), kinds[e["kind"]], json.dumps(e.get("pattern", "")), e.get("offset", 0), int(e.get("anchor", "0x0"), 16),
            e.get("disp_off", 0), e.get("insn_len", 0), e.get("addend", 0), json.dumps(e.get("iat", "")),
            ", ".join(e.get("used_in", []))[:90]))
    return "\n".join([
        "// GENERATED by tools/gen_rvas.py from rvas.json - do not edit. Pattern table behind Grva() (gamerva.h).",
        "#pragma once",
        "#include <stdint.h>",
        "#define GR_BUILD_TIMESTAMP %s" % doc["build"]["timestamp"],
        "#define GR_BUILD_SIZE_OF_IMAGE %s" % doc["build"]["size_of_image"],
        "enum { GRV_CODE, GRV_GLOBAL, GRV_IAT, GRV_NONE };",
        "typedef struct {",
        "    uint32_t rva;        // v2.02 RVA (sorted)",
        "    uint8_t kind;",
        "    const char* pattern;  // code: match starts offset bytes before rva; global: offset bytes before the anchor",
        "    int16_t offset;",
        "    uint32_t anchor;      // global: v2.02 RVA of the rip-relative instruction",
        "    uint8_t dispOff, insnLen;",
        "    int32_t addend;",
        "    const char* iat;      // iat: \"dll!func\"",
        "} GrDef;",
        "static const GrDef k_grdefs[] = {",
    ] + rows + [
        "};",
        "#define GR_COUNT ((int)(sizeof(k_grdefs) / sizeof(k_grdefs[0])))",
        "",
    ])


g.MOD, g.MODNAME = MOD, MOD.name
g.JSON, g.HDR = MOD / "rvas.json", MOD / "src" / "rvas_gen.h"
g.SKIP = ()
g.render = render
if __name__ == "__main__":
    sys.exit(g.main())
