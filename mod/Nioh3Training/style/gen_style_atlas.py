"""Style meter (human #126496/#126502): writes src/style_atlas_gen.h from style/rank_atlas.json.

The atlas PNG itself is embedded by the compiler (.incbin in style_meter_game.h) and decoded with WIC at run time;
this header only carries the sprite rectangles and draw hints. Run: py -I mod/Nioh3Training/style/gen_style_atlas.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RANKS = ("D", "C", "B", "A", "S", "SS", "SSS")


def main() -> int:
    with open(os.path.join(HERE, "rank_atlas.json"), encoding="utf-8") as f:
        atlas = json.load(f)
    sp = atlas["sprites"]
    w, h = atlas["size"]
    lines = [
        "// GENERATED by mod/Nioh3Training/style/gen_style_atlas.py from style/rank_atlas.json. Do not edit.",
        "// Sprite rectangles {x, y, w, h} in style/rank_atlas.png (approved set, Temp/rank126376, human #126376).",
        f"#define SM_ATLAS_W {w}",
        f"#define SM_ATLAS_H {h}",
        f"#define SM_LETTER_H_1080P {int(atlas['draw']['letter_height_1080p'])}",
        "static const int sm_atlas_letter[7][4] = {" + ", ".join("{%d, %d, %d, %d}" % tuple(sp["letter_" + r]) for r in RANKS) + "};",
        "static const int sm_atlas_word[7][4] = {" + ", ".join("{%d, %d, %d, %d}" % tuple(sp["word_" + r]) for r in RANKS) + "};",
        "static const int sm_atlas_gauge_bg[4] = {%d, %d, %d, %d};" % tuple(sp["gauge_bg"]),
        "static const int sm_atlas_gauge_fill[4] = {%d, %d, %d, %d};" % tuple(sp["gauge_fill"]),
    ]
    for r in RANKS:
        x, y, rw, rh = sp["letter_" + r]
        assert x + rw <= w and y + rh <= h, r
    out = os.path.join(HERE, "..", "src", "style_atlas_gen.h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
