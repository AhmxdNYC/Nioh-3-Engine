"""Export approved generator paths for the C/C++ GDI renderer (no font dependency)."""
from pathlib import Path
import importlib.util
root = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('stroke', root / 'mod/Nioh3EngineFix/tools/gen_font_stroke.py')
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
m.import_approved()
lines = ['// Generated by mod/shared/gen_gdi_stroke.py; same paths as gen_font_stroke.py.', '#pragma once', 'typedef struct { float x0,y0,x1,y1; } N3StrokeSegment;', 'typedef struct { unsigned short first,count; } N3StrokeGlyph;', 'static const N3StrokeSegment n3_stroke_segments[] = {']
indices=[]; at=0
for code in range(32,127):
    segs=m.GLYPHS[chr(code)];indices.append((at,len(segs)));at+=len(segs)
    for seg in segs:
        lines.append('    {' + ','.join(f'{v:.6f}f' for v in seg) + '},')
lines += ['};','static const N3StrokeGlyph n3_stroke_glyphs[95] = {']
lines += [f'    {{{a},{b}}},' for a,b in indices]
lines += ['};','']
(root / 'mod/shared/gdi_stroke_paths.h').write_text('\n'.join(lines))
print(f'Exported 95 glyphs / {at} segments')

# Same float4 layout uploaded directly to the OSD root constant buffer.
data=[(float(a),float(b),0.,0.) for a,b in indices]
data += [seg for code in range(32,127) for seg in m.GLYPHS[chr(code)]]
h=['// Generated by mod/shared/gen_gdi_stroke.py', '#pragma once', 'static const float n3_osd_strokes[][4] = {']
h += ['    {'+','.join(f'{v:.6f}f' for v in row)+'},' for row in data]
h += ['};','']
(root/'mod/shared/osd_stroke_data.h').write_text('\n'.join(h))
