"""Entrances chosen by a mission flag in script_main.

A row is emitted only when script_main pushes mission flag 187 into
Mission::IsMissionFlag, and the same script passes exactly two placement
constants to Mission::BossBattleMode. Flag 187 is the entrance selector
(Souji, or the Yoshinobu-only entrance). It is not a boss id. Other flags
with two BossBattleMode placements are separate fights and stay off this
table. The catalogue placement is the primary. The other BossBattleMode
placement is the alternate. The start is the catalogue stage_mission, and
it must be a start point in that mission's start-point table.
"""
import argparse, csv, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "re" / "scripts_re"))
sys.path.insert(0, str(ROOT / "tools"))
import lfm_disasm as dis
import rematch_catalog as cat
import gen_native_no_boss_mode as gnb

OUT = ROOT / "mod" / "Nioh3BossRematch" / "src" / "native_branch_entrances_gen.h"
ENTRANCE_FLAG = 187

def tables(lfm):
    cat.LFM = lfm
    b = cat.lfm(cat.IDTAB).read_bytes()
    ids = {}
    for i in range(struct.unpack_from("<I", b, 4)[0]):
        e = 8 + i * 8
        k, o = struct.unpack_from("<Ii", b, e)
        ids[k] = b[e + o:b.index(b"\0", e + o)].decode()
    b = cat.lfm(cat.MISSIONDB).read_bytes()
    missions = {}
    for i in range(struct.unpack_from("<I", b, 4)[0]):
        r = b[8 + i * 0x198:8 + (i + 1) * 0x198]
        missions[struct.unpack_from("<H", r, 0x158)[0]] = r
    def path(rec, off):
        name = ids.get(struct.unpack_from("<I", rec, off)[0])
        if not name:
            return None
        rel = name.lstrip("/")
        for arch in lfm.glob("archive_*"):
            p = arch / rel
            if p.exists():
                return p
        return None
    return missions, path

def start_ids(path):
    if not path:
        return set()
    t = path.read_bytes()
    if len(t) < 8 or t[:4] != b"\x00\x22\x04\x20":
        return set()
    count = struct.unpack_from("<I", t, 4)[0]
    if 8 + count * 0xA4 > len(t):
        return set()
    return {struct.unpack_from("<I", t, 8 + j * 0xA4)[0] for j in range(count)}

def flag_constants(script, pool, body):
    out = []
    for k in range(len(body) - 1):
        if body[k].op == 0x29 and body[k].args and gnb.call_name(script, pool, body, k + 1) == "Mission::IsMissionFlag":
            out.append(body[k].args[0])
    return out

def boss_mode_placements(script, pool, bodies):
    found = []
    for ins in bodies.values():
        for k in range(len(ins) - 1):
            if ins[k].op == 0x29 and ins[k].args and gnb.call_name(script, pool, ins, k + 1) == "Mission::BossBattleMode":
                found.append(ins[k].args[0])
    return sorted(set(found))

def generate(lfm):
    missions, path = tables(lfm)
    with (ROOT / "mod" / "Nioh3BossRematch" / "Nioh3BossRematch_bosses.tsv").open(encoding="utf-8") as f:
        catalogue = list(csv.DictReader((x for x in f if not x.startswith("#")), delimiter="\t"))
    cache = {}
    rows = []
    for r in catalogue:
        try:
            mid = int(r["replay_mission_id"], 0)
            placement = int(r["placement_id"])
            start = int(r["stage_mission"], 0)
        except ValueError:
            continue
        if mid not in missions or r["route"] not in ("R", "H", "D") or not start:
            continue
        script_path = path(missions[mid], 0x50)
        if not script_path:
            continue
        key = str(script_path)
        if key not in cache:
            script = dis.load(script_path)
            pool = gnb.strings(script)
            bodies = gnb.bodies_of(script)
            cache[key] = (script, pool, bodies, flag_constants(script, pool, bodies.get("script_main", [])), boss_mode_placements(script, pool, bodies))
        script, pool, bodies, flags, bosses = cache[key]
        if flags != [ENTRANCE_FLAG] or placement not in bosses or len(bosses) != 2:
            continue
        if start not in start_ids(path(missions[mid], 0x6C)):
            continue
        alt = bosses[0] if bosses[1] == placement else bosses[1]
        rows.append(dict(id=r["id"], mission=mid, start=start, placement=placement, alt=alt, flag=flags[0]))
    rows.sort(key=lambda r: (r["mission"], r["placement"], r["id"]))
    return rows

def render(rows):
    lines = [
        "// Generated by tools/gen_native_branch_entrances.py from mission scripts.",
        "// script_main tests one Mission::IsMissionFlag constant, and BossBattleMode",
        "// is called with the catalogue placement plus one other. The runtime has no",
        "// mission list of its own.",
        "#include <stdint.h>",
        "typedef struct { uint32_t mission, start, placement, alt; } NativeBranchEntrance;",
        "static const NativeBranchEntrance g_native_branch_entrances[] = {",
    ]
    for r in rows:
        lines.append("    {0x%Xu, %uu, %uu, %uu}, // %s flag %u" % (r["mission"], r["start"], r["placement"], r["alt"], r["id"], r["flag"]))
    if not rows:
        lines.append("    {0u, 0u, 0u, 0u},")
    lines += [
        "};",
        "inline uint32_t NativeBranchAlt(uint32_t mission, uint32_t start, uint32_t placement) {",
        "    for (unsigned i = 0; i < sizeof g_native_branch_entrances / sizeof *g_native_branch_entrances; ++i) {",
        "        const NativeBranchEntrance* e = &g_native_branch_entrances[i];",
        "        if (e->mission == mission && e->start == start && e->placement == placement) return e->alt;",
        "    }",
        "    return 0;",
        "}",
        "",
    ]
    return "\n".join(lines)

if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--lfm", type=Path, required=True)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    rows = generate(a.lfm)
    ids = [r["id"] for r in rows]
    if ids != ["R1DEA"]:
        sys.exit("branch entrances changed: %s" % ",".join(ids))
    text = render(rows)
    if a.check:
        assert OUT.read_text(encoding="utf-8") == text, OUT
    else:
        OUT.write_text(text, encoding="utf-8")
    print("branch entrances: %d" % len(rows))
    print(", ".join("%s flag %u alt %u" % (r["id"], r["flag"], r["alt"]) for r in rows))
