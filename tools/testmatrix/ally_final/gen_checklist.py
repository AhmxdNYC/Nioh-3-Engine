#!/usr/bin/env python3
"""gen_checklist.py - writes checklist.md (per-run checklist for the Ally final benchmark) from ../matrix.json.
  python3 gen_checklist.py > checklist.md
Sections: A header/preflight, B every mod flag alone (all Ally items of matrix.json), C dropped-experiment re-tests, D graphics
presets x {STOCK, MOD}, E per-setting levels, F latency, G stability. Game-side only; no TDP/governor/env/gamescope changes."""
import json, os, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
M = json.load(open(os.path.join(HERE, "..", "matrix.json"), encoding="utf-8-sig"))
items = [i for i in M["items"] if "ally" in i.get("devices", [])]
BOX = "[ ]"

# graphics keys swept one at a time (key -> levels) from cfgswitch.sh `levels`; REF = the MOD HIGH preset value
SWEEP = ["REN_RAT", "GI", "SHADOW_QUAL", "VOLUMETRIC", "AMBIENT_OCCLUSION", "SSR", "MOTION_BLUR", "POSTEFFECT_RESOLUTION",
         "LANDSCAPE_QUALITY", "VISUAL_EFFECT", "GRASS_DENSITY", "MODEL_DRAW", "MOTION_QUALITY", "MESHLET_QUALITY", "MODEL_QUAL",
         "SSS", "COLOR_PRECISION", "ANISOTROPIC_FILTER", "DEPTH_OF_FIELD", "BLOOM", "LENS_FLARE", "CHROMATIC_ABERRATION",
         "NOISE_FILTER", "VIGNETTING", "MACH_BAND_NOISE", "WIND_SENSITIVITY", "MODEL_TEX_QUAL"]


def levels(k):
    return subprocess.run(["bash", os.path.join(HERE, "cfgswitch.sh"), "levels", k], capture_output=True, text=True,
                          env={**os.environ, "NIOH3_CONFIG": "/dev/null"}).stdout.split()


def ini(i):
    return " ".join(f"{k}={v}" for _, k, v in i.get("needs", []) + i.get("ini", [])) or "-"


out = []
w = out.append
w("# Ally X final benchmark - per-run checklist (generated by gen_checklist.py; edit the generator, not this file)\n")
w("Rule: game-side only. No TDP / governor / env var / gamescope change. Same save, same spot, same camera sweep for every run "
  "(`notes/final-benchmark-protocol.md`). Tool order per run: `cfgswitch.sh` (graphics) -> ini/shaders -> launch -> "
  "`run_log.sh tag ID VARIANT PRESET` -> `run_log.sh run [combat]` -> screenshot if `shot` -> close game -> restore ALL-OFF.\n")
w("## A. Session preflight (once)\n")
for t in ["`./run_log.sh install` done, overlay visible in game; Shift_L+F2 starts/stops a log (or mapped in Steam Input)",
          "`export NIOH3_DIR=<game folder>`; `./cfgswitch.sh path` prints the config.xml; `./cfgswitch.sh backup session-start`",
          "`./ally_shaders.sh status all` (gpu-shaders) = nothing applied; ini = ALL-OFF (`matrix.json` `alloff`)",
          "Fixed for the whole session and written here: DISP_MODE ____ SCR_REZ 1920x1080 REN_FPS ____ VSYNC ____ DYNAMIC_RESOLUTION ____ "
          "RESOLUTION_SCALING ____ FRAME_GENERATION OFF  power mode/TDP ____ (record only, do not change)",
          "Battery: plugged in / ____ %; room temp ____ C; cool start (fan idle) before each BASE",
          "Temps are logged automatically (MangoHud cpu_temp/gpu_temp -> `summary_ally_hw.csv`); also note the Steam/Bazzite overlay reading on the first run of each section"]:
    w(f"- {BOX} {t}")
w("\nPer-run columns: `done`; `tag` = `run_log.sh tag <ID> <VARIANT> <PRESET>`; stand x2, move x1, combat x1 where marked; `shot` = same-view screenshot; "
  "`temps` = peak CPU/GPU C written from the summary.\n")

w("## B. Every mod flag (alone vs BASE; BASE#1 first, BASE#2 middle, BASE#3 last; risk=high last)\n")
w("| done | ID | grp | risk | mode | ini (+needs) | shaders/swap | windows | shot | wine | tag command | temps |")
w("|---|---|---|---|---|---|---|---|---|---|---|---|")
order = sorted(items, key=lambda i: (i["id"] != "BASE", i.get("risk") == "high", i.get("grp", 50)))
for i in order:
    if i["id"] in ("BASE",):
        for n in (1, 2, 3):
            w(f"| {BOX} | BASE#{n} | 0 | low | launch | ALL-OFF | - | stand x2, move | - | - | `tag BASE#{n} MOD USER` | |")
        continue
    if i.get("enabled") is False:
        continue
    win = "stand x2, move" + (", combat" if i.get("combat") else "") + (", load" if i.get("load") else "")
    sh = ",".join(i.get("shaders", []) + [f"swap:{s}" for s in i.get("swap", [])]) or "-"
    w(f"| {BOX} | {i['id']} | {i.get('grp', '')} | {i.get('risk', '')} | {i.get('mode', '')} | {ini(i)} | {sh} | {win} | "
      f"{'yes' if i.get('shot') else '-'} | {'yes' if i.get('wine_only') else '-'} | `tag {i['id']} MOD USER` | |")
w("\nLive items (`mode=live`) may share one launch (install with the `live_installed_value`, all off, BASE-live, then one at a time). "
  "Items marked `wine` need Proton; skip nothing on the Ally except PC-only ids (not listed).\n")

w("## C. Dropped-experiment re-tests (final protocol item 2; each on the Ally, one at a time vs BASE)\n")
w("Excluded and NOT built, so not re-tested: **VBC** (not exact), **HBAO draw merge** (nothing to merge), **ZI**, **RR1** (not provable). "
  "Source: STATUS.md 'Dropped-but-kept for the final re-test'.\n")
drop = [("GI shader rewrite #121 + #414", "S_gi", "shot"), ("Fog (VFSCAT) rewrite", "S_fog", "shot"), ("toonedge2", "S_toonedge2", ""),
        ("esm", "S_esm", ""), ("wdo28", "S_wdo28", ""), ("wdo14", "S_wdo14", ""), ("mpc", "S_mpc", ""), ("mshlod", "S_mshlod", ""), ("trvs", "S_trvs", ""),
        ("pbvs", "S_pbvs", ""), ("ghdm", "S_ghdm", ""), ("post-v1 swap 04c1", "X_04c1", "shot"), ("post-v1 swap 4e13", "X_4e13", "shot"),
        ("post-v1 swap cf79", "X_cf79", "shot"), ("post-v1 swap e6ef", "X_e6ef", "shot"), ("post-v1 swap f11a", "X_f11a", "shot"),
        ("R2a", "R2a", "shot"), ("R2b", "R2b", "shot"), ("R1 (barriers variant)", "R1g", "shot"), ("R1 (cpu)", "R1p", ""),
        ("AS0 (async slot 0)", "AS0", "combat shot"), ("LM (level-load memory)", "LM", "load"), ("RWb", "RWb", "load"),
        ("WG", "WG", "load"), ("GL1", "GL1", "load"), ("LC", "LC", "load"), ("LW", "LW", "load"),
        ("DropUndoPairs", "DropUndo", ""), ("TileBatch", "TileBatch", "load")]
ids = {i["id"] for i in items}
allids = {i["id"] for i in M["items"]}
w("| done | experiment | matrix id | extra | in matrix | tag command |")
w("|---|---|---|---|---|---|")
for name, mid, ex in drop:
    w(f"| {BOX} | {name} | {mid} | {ex or '-'} | {'yes' if mid in ids else ('PC-ONLY in matrix.json: add "ally" to devices (ini lines exist)' if mid in allids else 'NOT IN MATRIX')} | `tag {mid} MOD USER` |")
w("\nAll-shaders-on check (Ally 1.7.5 showed all replacements ON = 0.4-0.6 fps slower): `./ally_shaders.sh apply` one name at a time; `apply all` is banned.\n")

w("## D. Graphics presets x {STOCK, MOD ALL-KEPT}  (`cfgswitch.sh preset LOW|MID|HIGH|MAX`)\n")
w("STOCK = mod removed / all-off ini + no shaders. MOD = ALL-KEPT ini + kept shaders. Windows: stand x2, move, combat. Screenshots of the same view per preset (MOD).\n")
w("| done | ID | cfgswitch | variant | windows | shot | tag command | temps |")
w("|---|---|---|---|---|---|---|---|")
for p in ("LOW", "MID", "HIGH", "MAX"):
    for v in ("STOCK", "MOD"):
        w(f"| {BOX} | PRE_{p}_{v} | `preset {p}` | {v} | stand x2, move, combat | {'yes' if v == 'MOD' else '-'} | `tag PRE_{p}_{v} {v} {p}` | |")
w("")

w("## E. Per-setting levels (cost vs visual; MOD ALL-KEPT on the HIGH preset, change ONE key; REF = HIGH-preset value)\n")
w("Start: `cfgswitch.sh preset HIGH`, run `SET_<KEY>@REF`, then `cfgswitch.sh set KEY LEVEL` per level, then `preset HIGH` again. "
  "stand x2 + move; screenshot per level (same view) to judge the visual change.\n")
w("| done | key | levels to run | run ids |")
w("|---|---|---|---|")
for k in SWEEP:
    lv = levels(k)
    w(f"| {BOX} | {k} | {' '.join(lv)} | `SET_{k}@REF` " + " ".join(f"`SET_{k}@{l}`" for l in lv) + " |")
w("")

w("## F. Input latency (`latency_procedure.md`)\n")
for c in ("STOCK", "OPTIMIZED", "OPTIMIZED_FG"):
    w(f"- {BOX} {c}: clip filmed (24 presses), `run_log.sh tag LAT_{c} {c} USER; run_log.sh window lat`, frames counted into latency.csv")
w(f"- {BOX} STOCK repeated, medians agree within 1 frame; `python3 latency_calc.py latency.csv` saved\n")

w("## G. Stability (the user plays; recommended setup)\n")
for t in ["Session start: time ____, config.xml backup `stability-start`, ini hash ____", "Crashes / hangs: ____ (copy `Nioh3EngineFix.log` tail + the game exit code from the Steam/proton log)",
          "Session end: duration ____ h; peak temps ____; MangoHud one long log (`window load`)"]:
    w(f"- {BOX} {t}")
print("\n".join(out))
