"""Offline check of the Training roster (kind 'summon') rows in Nioh3Training_arenas.tsv.

The original generator for these rows (#22984) was never committed. Since #23451 the rows are
generated by tools/auto_arena.py (roster block), which needs the game archives
(`py tools/auto_arena.py --check` on a machine with the game). This module replaces the missing
file for run_move_toggle_tests.py (#98173): generate() re-emits every summon row in the exact
format auto_arena.py writes, so a hand edit or a format drift fails; validate() checks the rules.
No game data, no per-boss rule.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TSV = ROOT / "mod/Nioh3Training/Nioh3Training_arenas.tsv"


def _summon(text):
    for line in text.split("\n"):
        c = line.split("\t")
        if not line.startswith("#") and len(c) >= 15 and c[12] == "summon":
            yield line, c


def row(mission, chr_, rid, name):
    """One roster row, the same columns auto_arena.py writes (mission 0, no arena/player/boss point)."""
    return "\t".join([mission if mission else "0", "0", "0x00", str(chr_), "0", "0", "0", "0", "0.0", "0", "0", "0", "summon", rid, name])


def generate(text=None):
    """Return the table with every summon row re-emitted in auto_arena.py's format; other lines unchanged."""
    text = TSV.read_text(encoding="utf-8") if text is None else text
    out = []
    for line in text.split("\n"):
        c = line.split("\t")
        if not line.startswith("#") and len(c) >= 15 and c[12] == "summon" and c[3].isdigit():
            line = row(c[0], int(c[3]), c[13], c[14])
        out.append(line)
    return "\n".join(out)


def validate(text=None):
    text = TSV.read_text(encoding="utf-8") if text is None else text
    rows = list(_summon(text))
    assert rows, "no summon rows"
    ids, chrs = set(), set()
    for line, c in rows:
        assert len(c) == 15, "summon row has %d columns: %s" % (len(c), line)
        assert c[3].isdigit() and int(c[3]) > 0, "bad boss char id: %s" % line
        assert c[0] == "0" or re.fullmatch(r"0x[0-9A-Fa-f]{1,4}", c[0]), "bad mission: %s" % line
        if c[0] == "0":
            assert c[13] == "S" + c[3], "mission-0 summon id must be S<chr>: %s" % line
        assert c[14].strip(), "summon row without a name: %s" % line
        assert c[13] not in ids, "duplicate summon id %s" % c[13]
        ids.add(c[13])
        key = (c[0], c[3])
        assert key not in chrs, "duplicate summon character %s" % (key,)
        chrs.add(key)
    return len(rows)


if __name__ == "__main__":
    t = TSV.read_text(encoding="utf-8")
    n = validate(t)
    ok = t == generate(t)
    print("%s: %d summon rows%s" % ("PASS" if ok else "FAIL", n, "" if ok else " (format drift; regenerate with tools/auto_arena.py)"))
    sys.exit(0 if ok else 1)
