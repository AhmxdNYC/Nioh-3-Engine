"""Yoritomo (chr 16102) per-move summary, static and read-only.  Run: py -I tools/yoritomo_move_summary.py [action_file] [out_csv]

Rules (notes/yoritomo-moves-unblockable-22305.md, all PROVEN as data):
  unblockable = GreatAttack flag = bit 0x2000 of u16 at action row +0x04
  hitbox rows = sub-table 2 (192 B); owned rows = sub-table 0 packed records (u16 count + row indexes), see chr_hit_groups.py
  row +0x08 start frame (FFFF = never started), +0x0C length, +0xA5 hit id; active = [start, start+len-1]
  own_hit_count = number of distinct +0xA5 ids among owned rows with a started window
  windows = one (first,last) per hit id (union of that id's rows)
NOT KNOWN: recovery frames, hit counts of spawned projectiles (own_hit_count only covers the move's own hitbox rows).
Names: the existing action-fields csv has no name column, so name is blank unless a mapping is added.
"""
import csv
import importlib.util
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, 'data', 'extract', 'lfm', 'archive_01', 'FA',
                    '5FBD421BF96B8514DA056584B9507A22DC7956B1793995A113FBA714CFFA54')
SORT = os.path.join(os.path.dirname(ROOT), 'nioh3-sort-20999')


def find(*cands):
    for c in cands:
        if os.path.exists(c):
            return c
    raise SystemExit('missing: ' + cands[0])


def load_table_module():
    p = find(os.path.join(HERE, 'chr_action_table.py'), os.path.join(SORT, 'tools', 'chr_action_table.py'))
    spec = importlib.util.spec_from_file_location('chr_action_table', p)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def write_groups(rows, out):
    atk = [r for r in rows if r['is_attack']]
    g = {'Unblockable (GreatAttack)': [r for r in atk if r['unblockable']]}
    rest = [r for r in atk if not r['unblockable']]
    for t, f in (('1-hit', lambda n: n == 1), ('2-hit', lambda n: n == 2), ('3-hit', lambda n: n == 3),
                 ('4+-hit', lambda n: n >= 4), ('0-own-hit (projectile/other)', lambda n: n == 0)):
        g[t] = [r for r in rest if f(r['own_hit_count'])]
    L = ['# Yoritomo moves grouped by own hit count (generated by tools/yoritomo_move_summary.py)', '',
         'Source: action file sub-tables 0/1/2; rules from notes/yoritomo-moves-unblockable-22305.md. Detail: notes/yoritomo-move-summary.csv.', '',
         '**UNKNOWN:** recovery frames, and hit counts of spawned projectiles. "Hits" = distinct hit ids (+0xA5) among the move\'s',
         'own hitbox rows only. Moves with projectile spawns (marked `proj`) can hit more than listed. Moves are not named (no name data exists).',
         'The unblockable group is listed first and is excluded from the other groups.', '']
    for t, rs in g.items():
        L += ['## %s: %d moves' % (t, len(rs)), '']
        for r in rs:
            L.append('- %s anim %s, %d hit%s, windows %s%s' % (
                r['action_id'], r['animation'], r['own_hit_count'], '' if r['own_hit_count'] == 1 else 's',
                r['active_windows'] or '-', ', proj' if r['projectile_spawns'] == 'y' else ''))
        L.append('')
    L.append('## Non-attacks: %d moves' % (len(rows) - len(atk)))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L) + '\n')
    print({t: len(v) for t, v in g.items()}, 'non-attacks', len(rows) - len(atk))


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DATA
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'notes', 'yoritomo-move-summary.csv')
    cat = load_table_module()
    meta = {r['action_id']: r for r in cat.full(path)}
    try:
        names = {}
        with open(find(os.path.join(ROOT, 'notes', 'yoritomo-action-fields.csv'),
                       os.path.join(SORT, 'notes', 'yoritomo-action-fields.csv')), encoding='utf-8') as f:
            for r in csv.DictReader(f):
                n = r.get('name') or r.get('move_name') or ''
                if n:
                    names[r['action_id']] = n
    except SystemExit:
        names = {}
    d = open(path, 'rb').read()
    st = [struct.unpack_from('<II', d, 4 + 8 * i) for i in range(16)]
    o0, s0 = st[0]
    o1, s1 = st[1]
    o2 = st[2][0]
    na = s1 // 0x150
    sizes = struct.unpack_from('<%dH' % na, d, o0 + 64)
    p = o0 + s0 - sum(sizes)
    rows = []
    for r in range(na):
        cnt = struct.unpack_from('<H', d, p)[0]
        idx = struct.unpack_from('<%dH' % cnt, d, p + 2)
        p += sizes[r]
        ro = o1 + r * 0x150
        aid = struct.unpack_from('<H', d, ro + 0x0C)[0]
        f04 = struct.unpack_from('<H', d, ro + 0x04)[0]
        is_atk = any(struct.unpack_from('<H', d, ro + x)[0] != 0xFFFF for x in (0x13C, 0x142))
        ids = {}
        for i in idx:
            b = o2 + i * 192
            start, ln = struct.unpack_from('<H', d, b + 8)[0], struct.unpack_from('<H', d, b + 0x0C)[0]
            if start == 0xFFFF:
                continue
            end = start + max(ln, 1) - 1
            hid = d[b + 0xA5]
            lo, hi = ids.get(hid, (start, end))
            ids[hid] = (min(lo, start), max(hi, end))
        wins = sorted(ids.values())
        m = meta['0x%X' % aid]
        rows.append({
            'action_id': '0x%X' % aid, 'name': names.get('0x%X' % aid, ''), 'is_attack': int(is_atk),
            'animation': m['motion'], 'unblockable': int(bool(f04 & 0x2000)),
            'own_hit_count': len(ids), 'active_windows': ' '.join('%d-%d' % w for w in wins),
            'owned_hitbox_rows': cnt,
            'projectile_spawns': 'y' if m['event_action_links'] else 'n', 'next_move': m['next_action'],
        })
    with open(out, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    by = {r['action_id']: r for r in rows}
    for k, hits, wins, unb in (('0x4E6E', 2, '96-106 143-157', 1), ('0x4E68', 3, None, 0), ('0x4E6C', 2, None, 0)):
        r = by[k]
        assert r['own_hit_count'] == hits and r['unblockable'] == unb and (wins is None or r['active_windows'] == wins), r
    write_groups(rows, os.path.join(os.path.dirname(out), 'yoritomo-move-groups.md'))
    print('rows', len(rows), 'sanity ok ->', out)
    return rows


if __name__ == '__main__':
    main()
