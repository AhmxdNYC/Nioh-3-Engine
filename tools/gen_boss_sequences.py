"""Generate mod/boss_sequences.h: the decoded 'next action on finish' links (+0xE0 of the action record, notes/yoritomo-action-fields.md).

user #14317: the Boss moves 'Sequences' sub menu chains these links (head -> next -> ... until idle / a loop). Only links to a real
move are kept (not 0 / idle 0x2 / alt idle 0x3F1, not a self loop: loops are flagged instead).
    py -I tools/gen_boss_sequences.py          (write)
    py -I tools/gen_boss_sequences.py --check  (exit 1 when the header is out of date)
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [(16102, ROOT / 'notes/yoritomo-action-fields.csv')]  # (chr, action-field CSV from tools/chr_action_table.py --csv)
IDLE = {0x0, 0x2, 0x3F1}


def generate():
    lines = ['// Generated by tools/gen_boss_sequences.py from the decoded action records (+0xE0 = next action on finish, PROVEN).',
             '// user #14317: the Boss moves "Sequences" sub menu chains these links. loop = the next action repeats itself (looping middle part).',
             '#pragma once', '#include <stdint.h>',
             'typedef struct { uint32_t chr, id, next; unsigned char loop; } N3Next;',
             'static const N3Next kN3Next[] = {']
    n = 0
    for chr_id, path in SOURCES:
        with path.open(encoding='utf-8-sig', newline='') as f:
            rows = list(csv.DictReader(f))
        nxt = {int(r['action_id'], 16): int(r['next_action'], 16) for r in rows if r.get('next_action')}
        for a in sorted(nxt):
            b = nxt[a]
            if b in IDLE or b == a:
                continue
            lines.append('    {%du, 0x%Xu, 0x%Xu, %d},' % (chr_id, a, b, 1 if nxt.get(b) == b else 0))
            n += 1
    lines += ['};', '#define N3_NEXT_COUNT ((int)(sizeof kN3Next / sizeof kN3Next[0]))', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    out = ROOT / 'mod/boss_sequences.h'
    text = generate()
    if '--check' in sys.argv:
        ok = out.exists() and out.read_text(encoding='utf-8') == text
        print('boss_sequences.h ' + ('up to date' if ok else 'OUT OF DATE'))
        sys.exit(0 if ok else 1)
    out.write_text(text, encoding='utf-8')
