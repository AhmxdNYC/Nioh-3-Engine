"""Generate mod/Nioh3Training/src/move_motion.h: action id -> motion id from the decoded action records.

user #14702 / #14710: a sequence repeat lets the game's own follow-up picks play (the next piece of the same attack: Yoritomo
0x4E78 > 0x4E79 > 0x4E7A > 0x4E8D are motions 1102 > 1103 > 1104 > 1104) and refuses picks of another attack. The motion family
(motion / 10) is read from notes/<boss>-action-fields.csv (column "motion", PROVEN record decode).
Usage: py tools/gen_move_motion.py [--write]
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [(16102, ROOT / 'notes/yoritomo-action-fields.csv')]  # (character id, decoded action records)
OUT = ROOT / 'mod/Nioh3Training/src/move_motion.h'


def generate() -> str:
    rows = []
    for chr_id, path in SOURCES:
        with path.open(newline='', encoding='utf-8') as f:
            seen = set()
            for r in csv.DictReader(f):
                aid, mot = int(r['action_id'], 16), int(r['motion'] or 0)
                if aid in seen or not mot:
                    continue
                seen.add(aid)
                rows.append((chr_id, aid, mot))
    rows.sort()
    lines = [
        '// Generated by tools/gen_move_motion.py from the decoded action records (notes/*-action-fields.csv, motion column).',
        '// user #14702 / #14710: move_toggle.h MvMotion: pieces of one attack share a motion family (motion / 10).',
        '#pragma once',
        '#include <stdint.h>',
        'typedef struct { uint32_t chr; uint16_t id, motion; } N3Motion;',
        'static const N3Motion kN3Motion[] = {',
    ]
    lines += ['    {%du, 0x%Xu, %du},' % r for r in rows]
    lines += ['};', '#define N3_MOTION_COUNT ((int)(sizeof kN3Motion / sizeof kN3Motion[0]))', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = generate()
    if '--write' in sys.argv:
        OUT.write_text(text, encoding='utf-8', newline='\n')
        print('wrote', OUT, text.count('\n    {'), 'rows')
    else:
        sys.stdout.write(text)
