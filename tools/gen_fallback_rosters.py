"""Generate fallback-only multi-boss rosters from extracted game data (#71960).

Catalogue boss names -> boss-names.csv char_id -> same mission enemy-index key64.
Training spawns key64, NOT the name-table char_id. Prefer boss-flag (0x4)
placements when variants exist; never guess between distinct remaining keys.
Order is catalogue order, a sequential fallback policy, NOT recovered script order.
Native route and existing arena table are untouched. --check verifies checked-in output.
"""
import argparse
import csv
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAX_BOSSES = 16


def read_csv(path, delimiter=','):
    with path.open(encoding='utf-8') as stream:
        return list(csv.DictReader((line for line in stream if not line.startswith('#')), delimiter=delimiter))


def resolve(catalogue, names, enemies):
    by_name = {}
    by_mission = {}
    for row in names:
        by_name.setdefault(row['english_name'].strip().casefold(), set()).add(int(row['char_id']))
    for row in enemies:
        by_mission.setdefault(int(row['mission_id'], 0), []).append(row)
    results = []
    for row in catalogue:
        if ';' not in row['boss']:
            continue
        parts = [name.strip() for name in row['boss'].split(';') if name.strip()]
        members, errors = [], []
        try:
            mission = int(row['replay_mission_id'], 0)
            selected = int(row['placement_id'], 0)
        except ValueError:
            mission, selected = 0, 0
        for name in parts:
            ids = by_name.get(name.casefold(), set())
            matches = [enemy for enemy in by_mission.get(mission, []) if int(enemy['char_id']) in ids]
            boss_matches = [enemy for enemy in matches if int(enemy['flags9c'], 0) & 4]
            preferred = boss_matches or matches
            keys = {int(enemy['key64']) for enemy in preferred}
            member = {'name': name, 'candidates': [dict(enemy) for enemy in matches]}
            if len(keys) != 1:
                member['error'] = 'no same-mission match' if not keys else 'ambiguous same-mission boss variants'
                errors.append(name + ': ' + member['error'])
            else:
                chosen = min(preferred, key=lambda enemy: (int(enemy['placement_id']) != selected, int(enemy['placement_id'])))
                member.update(chr=int(chosen['key64']), placement=int(chosen['placement_id']), name_char_id=int(chosen['char_id']))
            members.append(member)
        if len(parts) > MAX_BOSSES:
            errors.append('roster exceeds capacity')
        results.append({'id': row['id'], 'mission': mission, 'members': members, 'errors': errors})
    return results


def render_header(results):
    lines = ['// Generated by tools/gen_fallback_rosters.py; do not edit by hand.',
             '// Source: catalogue + boss-names.csv + same-mission rematch-enemy-index.csv.',
             '// Sequential catalogue order is fallback policy; native scripts are not modified.',
             '#ifndef NIOH3_FALLBACK_ROSTERS_GEN_H', '#define NIOH3_FALLBACK_ROSTERS_GEN_H',
             '#include <stdint.h>', '#include <string.h>', f'#define FALLBACK_ROSTER_MAX {MAX_BOSSES}',
             'typedef struct { const char* id; unsigned count; uint32_t chr[FALLBACK_ROSTER_MAX], placement[FALLBACK_ROSTER_MAX]; } FallbackRoster;',
             'static const FallbackRoster g_fallback_rosters[] = {']
    for row in results:
        if row['errors']:
            lines.append('    {"%s", 0, {0}, {0}}, // unresolved: %s' % (row['id'], '; '.join(row['errors'])))
        else:
            lines.append('    {"%s", %d, {%s}, {%s}},' % (row['id'], len(row['members']), ', '.join(str(m['chr'])+'u' for m in row['members']), ', '.join(str(m['placement'])+'u' for m in row['members'])))
    lines += ['};', 'static const FallbackRoster* FallbackRosterFind(const char* id) {',
              '    unsigned i; if (!id) return 0;',
              '    for (i = 0; i < sizeof g_fallback_rosters / sizeof g_fallback_rosters[0]; ++i)',
              '        if (!strcmp(id, g_fallback_rosters[i].id)) return &g_fallback_rosters[i];',
              '    return 0;', '}']
    # Observation may cover ambiguous variants without choosing one to spawn.
    lines += ['typedef struct { const char* id; uint32_t chr, placement; } NativeRosterCandidate;',
              'static const NativeRosterCandidate g_native_roster_candidates[] = {']
    for row in results:
        candidates = sorted({(int(c['key64']), int(c['placement_id'])) for m in row['members'] for c in m['candidates']})
        for chr_id, placement in candidates:
            lines.append('    {"%s", %du, %du},' % (row['id'], chr_id, placement))
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


def generate(root):
    results = resolve(read_csv(root/'mod/Nioh3BossRematch/Nioh3BossRematch_bosses.tsv', '\t'),
                      read_csv(root/'notes/boss-names.csv'), read_csv(root/'notes/rematch-enemy-index.csv'))
    report = {'sources': ['mod/Nioh3BossRematch/Nioh3BossRematch_bosses.tsv', 'notes/boss-names.csv', 'notes/rematch-enemy-index.csv'],
              'policy': 'sequential catalogue order; same-mission name match; prefer boss flag0x4; reject distinct remaining key64 variants; equivalent placements prefer catalogue selected then lowest placement ID',
              'script_schedule_recovered': False, 'rows': results}
    return {'mod/Nioh3Training/src/fallback_rosters_gen.h': render_header(results),
            'notes/fallback-rosters-71960.json': json.dumps(report, indent=2, ensure_ascii=True)+'\n'}, results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, rows = generate(args.root)
    stale = []
    for filename, text in outputs.items():
        path = args.root / filename
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(filename)
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
    unresolved = [row['id'] for row in rows if row['errors']]
    print(f'{len(rows)} multi-boss rows; {len(rows)-len(unresolved)} resolved; unresolved: {", ".join(unresolved) or "none"}')
    if stale:
        print('OUT OF DATE: ' + ', '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
