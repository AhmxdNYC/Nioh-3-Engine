# Generates notes/boss-movesets.md (pc2 #9334): static join boss -> candidate character assets -> action-object count.
import csv, re
bosses = list(csv.DictReader(open('notes/rematch-all-bosses.csv', encoding='utf-8')))
assets = list(csv.DictReader(open('notes/boss-char-assets.csv', encoding='utf-8')))
def info(x):
    f = x['asset_ids_files']
    m = re.search(r'n_actions=(\d+)', f)
    return (int(m.group(1)) if m else None, 'setting=' + re.search(r'setting_db=(\w+)', f).group(1) if 'setting_db=' in f else '')
STOP = {'the', 'and', 'of', 'no', 'novice', 'adept', 'veteran', 'demon', 'death', 'veil', 'great', 'minamoto', 'takeda', 'tokugawa', 'kunimatsu', 'baba', 'saito', 'hattori'}
def toks(s):
    s = re.sub(r'\(.*?\)', ' ', s)
    return [w for w in re.findall(r'[a-z]+', s.lower()) if len(w) >= 4 and w not in STOP]
def norm(s): return re.sub(r'[^a-z]', '', s.lower())
rows = []
for b in bosses:
    names = [n.strip() for n in re.split(r'\s*&\s*|;', re.sub(r'\(.*?\)', '', b['boss'])) if n.strip()]
    for n in names:
        t = toks(n)
        hit = []
        for a in assets:
            nm = a['name']
            if re.match(r'(EV_|CP_|FACE|CAP_)', nm): continue
            body = norm(re.sub(r'^[A-Z]{1,3}_', '', nm))
            hint = norm(a['name_hint'])
            if any((w in body) or (w in hint and a['name_hint'] != '(no name)') for w in t) and info(a)[0]:
                hit.append(a)
        rows.append((b, n, hit))
out = ['# Boss move lists - static status for all bosses (pc2 #9334)', '',
       'Generated by `tools/pc2/boss_movesets_gen.py` from `notes/rematch-all-bosses.csv` x `notes/boss-char-assets.csv` (pc2 has no `data/extract`; no game launched).', '',
       '## What can and cannot be said (read first)', '',
       '- **Per boss we can list the candidate character assets and their action-object count** (`MotorCharacterSetting` `CharacterActionObjectNameHashArray`). That count is the size of the asset\'s action set - an upper bound for moves, NOT a count of attacks (it includes idles, walks, hit reactions, deaths).',
       '- **No move NAMES or transition IDs exist statically.** Action objects are 32-bit name hashes; the Yamagata work (`training-yamagata-move-selection.md`) proved hash != transition ID and no hash->label dictionary is known. `9A732C(component, actionID)` stores an ID without lookup; the ID->move mapping is unproven.',
       '- So a labelled move list per boss (as the Yamagata drill wants) is **blocked on the same two items for every boss**: (1) hash/ID -> real action mapping via the state+0x2E4 consumer / `49B054` lookup, (2) a labelled source (animation names in strings, or live observation of `358528` current-action id while the boss fights). Everything Yamagata-specific in the contract/idle notes applies to every boss unchanged; do not reuse one boss\'s IDs for another (CN_ vs CE_ variants differ: Yamagata CN_MASAKAGE 78 actions vs CE_MASAKAGE_00 absent).',
       '- Practical path to real move lists: log `358528` (current action id, state+0xE8) at ~20 Hz during a fight per boss in Boss Rematch, then bucket by id; labels come from watching video/anim once per id. This needs game time (not done here).', '',
       '## Table (name match only - confidence LOW-MEDIUM; verify variant before use)', '',
       '| Boss (catalogue row) | Mission | Candidate assets : action objects (setting DB) |', '|---|---|---|']
nohit = []
for b, n, hit in rows:
    if hit:
        c = '; '.join(f"{a['name']}:{info(a)[0]} ({info(a)[1].replace('setting=','')})" for a in hit[:8]) + (' ...' if len(hit) > 8 else '')
        out.append(f"| {n} | {b['mission_id']} {b['mission_name']} | {c} |")
    else:
        nohit.append(f"{n} ({b['mission_id']})")
out += ['', '## Bosses with no candidate asset that has actions (no name match, or the asset is a 0-action stub / loader absent from the package)', '', ', '.join(sorted(set(nohit))) or '(none)', '',
        '## Notes', '', '- Stub settings (2788 bytes, 0 actions) exist for many CS_/CN_ boss names: their gameplay moveset sits under a different (CE_/KY_) asset or in the 104 loader DBs absent from the package.',
        '- Multi-boss missions list each boss separately; shared humanoid movesets (`CP_HUMAN_<weapon>`, 2958 actions) are excluded as they are weapon libraries, not boss kits.']
open('notes/boss-movesets.md', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(rows), sum(1 for r in rows if r[2]), 'matched')
