"""Generate the shared Training move catalogue from the recorded action CSV."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    with (ROOT / 'notes/boss-action-ids-all.csv').open(encoding='utf-8-sig', newline='') as f:
        rows = list(csv.DictReader(f))
    seen = set()
    lines = ['// Generated by tools/gen_boss_moves.py; labels are unverified observations.',
             '#pragma once', '#include <stdint.h>',
             '// kind (#13786, from tools/rematch/actlog_moves.py over Training logs): A attack (player hit seen), S wind-up that leads into a hit,',
             '// L combo link / fragment, T twitch (state change, ends at once when forced), M movement / system, I idle, 0 = not classified yet.',
             '// ms = typical natural run time (0 = unknown). T / L / M rows are hidden in the Training move list unless "Show twitches" is ON.',
             'typedef struct { uint32_t chr, id; const char *boss, *label; char kind; unsigned short ms; } N3Move;',
             'static const N3Move kN3Moves[] = {']
    for r in rows:
        chr_id, action = int(r['chr']), int(r['action_id'], 0)
        assert (chr_id, action) not in seen, 'Duplicate boss/action pair'
        seen.add((chr_id, action))
        kind = (r.get('kind') or '').strip()
        assert kind in ('', 'A', 'S', 'L', 'T', 'M', 'I', '?'), 'Unknown move kind %r' % kind
        typ = int(r.get('typ_ms') or 0)
        lines.append('    {%du, 0x%Xu, %s, %s, %s, %d},' % (
            chr_id, action, json.dumps(r['boss']), json.dumps(r.get('label_lowconf', '')),
            "'%s'" % kind if kind and kind != '?' else '0', min(typ, 65535)))
    lines += ['};', '#define N3_MOVE_COUNT ((int)(sizeof kN3Moves / sizeof kN3Moves[0]))',
              'static inline int N3MoveFind(uint32_t chr, uint32_t id) {',
              '    for (int i = 0; i < N3_MOVE_COUNT; ++i)',
              '        if (kN3Moves[i].chr == chr && kN3Moves[i].id == id) return i;',
              '    return -1;', '}',
              '// Initialization and idle are required by the veto fallback.',
              'static inline int N3MoveProtected(uint32_t id) { return id == 0 || id == 2; }',
              '// #13786: twitches, combo fragments and movement states are hidden from the move list by default.',
              "static inline int N3MoveTwitch(const N3Move* m) { return m->kind == 'T' || m->kind == 'L' || m->kind == 'M'; }", '']
    return '\n'.join(lines)


if __name__ == '__main__':
    (ROOT / 'mod/boss_moves.h').write_text(generate(), encoding='utf-8')
