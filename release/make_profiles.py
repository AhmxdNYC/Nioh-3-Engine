"""Build Nioh3EngineFix.ini profiles (today one: ALL = every Windows PC and Linux/Proton device) from the base ini + release\\profiles.json.

  py -I release\\make_profiles.py            write release\\profiles\\Nioh3EngineFix.<DEV>.ini (generated, gitignored:
                                            package.py regenerates them from the base ini of the build it packages)
  py -I release\\make_profiles.py --check    validate only: exit 1 if an override key is missing from the base ini
  py -I release\\make_profiles.py --list     print the overrides per device with status

Values are replaced in place (the base ini's comments stay), so a profile is the base ini plus a header and the
changed lines. A key that appears in a duplicated section (e.g. two [Memory] blocks) is changed in every copy.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = ROOT / "mod" / "Nioh3EngineFix" / "Nioh3EngineFix.ini"
PROFILES = ROOT / "release" / "profiles.json"
OUTDIR = ROOT / "release" / "profiles"

SEC_RE = re.compile(r"^\s*\[([^\]]+)\]\s*$")
KEY_RE = re.compile(r"^(\s*)([A-Za-z0-9_]+)(\s*=\s*)([^;\r\n]*?)(\s*)$")


def mod_version():
    src = (ROOT / "mod" / "Nioh3EngineFix" / "src" / "dllmain.cpp").read_text(encoding="utf-8", errors="replace")
    m = re.search(r'#define MOD_VERSION "([^"]+)"', src)
    return m.group(1) if m else "?"


def load_profiles():
    return {k: v for k, v in json.loads(PROFILES.read_text(encoding="utf-8")).items() if not k.startswith("_")}


def build(dev, prof, base_lines, version):
    want = {(o["section"].lower(), o["key"].lower()): o for o in prof["overrides"]}
    hit = set()
    out, sec = [], None
    for line in base_lines:
        m = SEC_RE.match(line)
        if m:
            sec = m.group(1).strip().lower()
            out.append(line)
            continue
        k = KEY_RE.match(line)
        if k and sec is not None and (sec, k.group(2).lower()) in want:
            o = want[(sec, k.group(2).lower())]
            hit.add((sec, k.group(2).lower()))
            line = f"{k.group(1)}{k.group(2)}{k.group(3)}{o['value']}{k.group(5)}"
        out.append(line)
    missing = [f"[{o['section']}] {o['key']}" for kk, o in want.items() if kk not in hit]
    head = [
        f"; ===== Nioh3EngineFix {version} - {dev} profile: {prof['title']} =====",
        "; Generated by release\\make_profiles.py from mod\\Nioh3EngineFix\\Nioh3EngineFix.ini + release\\profiles.json.",
        "; Rename to Nioh3EngineFix.ini next to Nioh3EngineFix.asi. Changed from the base ini:",
    ]
    for o in prof["overrides"]:
        head.append(f";   [{o['section']}] {o['key']} = {o['value']}  ({o['status']}: {o['why']})")
    head.append(";")
    return head + out, missing


def main(argv):
    base_text = BASE.read_text(encoding="utf-8-sig", errors="replace")
    base_lines = [l.rstrip(chr(13)) for l in base_text.split(chr(10))]
    if base_lines and base_lines[-1] == "":
        base_lines.pop()
    version = mod_version()
    profs = load_profiles()
    if "--list" in argv:
        for dev, p in profs.items():
            print(f"{dev}: {p['title']}")
            for o in p["overrides"]:
                print(f"  {o['status']:<11} [{o['section']}] {o['key']} = {o['value']}")
        return 0
    check = "--check" in argv
    rc = 0
    for dev, p in profs.items():
        lines, missing = build(dev, p, base_lines, version)
        if missing:
            print(f"ERROR {dev}: override keys not in the base ini: {', '.join(missing)}")
            rc = 1
            continue
        if check:
            print(f"OK    profile {dev}: all {len(p['overrides'])} override keys found in the base ini")
            continue
        text = "\r\n".join(lines) + "\r\n"
        path = OUTDIR / f"Nioh3EngineFix.{dev}.ini"
        OUTDIR.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        prov = sum(o["status"] == "provisional" for o in p["overrides"])
        print(f"wrote {path.relative_to(ROOT)} ({len(p['overrides'])} overrides, {prov} provisional)")
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
